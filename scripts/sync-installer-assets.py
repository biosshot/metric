#!/usr/bin/env python3
"""Generate backend deployment variants from the existing Mongo resource profiles."""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def assets() -> dict[str, str]:
    source = (ROOT / 'deploy/compose.yml').read_text(encoding='utf-8')
    app_and_symbols = source[source.index('  metric:'):source.index('\nvolumes:')]
    pg_service = '''  postgres:
    image: postgres:18.6-bookworm@sha256:afc7e2d441324c0388fa80c3d24f733b4194a4eb7f47dd8ee2b08eb1a24a647c
    restart: unless-stopped
    mem_limit: ${METRIC_POSTGRES_MEMORY_LIMIT:-512m}
    environment:
      POSTGRES_USER: metric
      POSTGRES_DB: metric
      POSTGRES_PASSWORD: ${METRIC_POSTGRES_PASSWORD:?set in .env}
    volumes:
      - postgres-data:/var/lib/postgresql
    healthcheck:
      test: [CMD-SHELL, "pg_isready -U metric -d metric"]
      interval: 5s
      timeout: 3s
      retries: 30
    logging: *default-logging

'''
    header = source[:source.index('  mongodb:')]
    result: dict[str, str] = {}
    for backend, mode in [('postgres', 'bundled'), ('postgres', 'external'), ('mongodb', 'external')]:
        body = app_and_symbols
        if mode == 'bundled':
            body = body.replace('      mongodb:', '      postgres:')
        else:
            body = body.replace('      mongodb:\n        condition: service_healthy\n', '')
        uri_line = '      MONGODB_URI: mongodb://metric:${METRIC_MONGO_PASSWORD}@mongodb:27017/?authSource=admin'
        if backend == 'postgres':
            uri = 'postgres://metric:${METRIC_POSTGRES_PASSWORD}@postgres:5432/metric' if mode == 'bundled' else '${METRIC_POSTGRES_URI:?set in .env}'
            body = body.replace(uri_line, '      METRIC_POSTGRES_URI: ' + uri)
        else:
            body = body.replace(uri_line, '      MONGODB_URI: ${MONGODB_URI:?set in .env}')
        body = body.replace('    environment:\n      ' + ('METRIC_POSTGRES_URI:' if backend == 'postgres' else 'MONGODB_URI:'),
                            '    env_file: [./connection.env]\n    environment:\n      ' + ('METRIC_POSTGRES_URI:' if backend == 'postgres' else 'MONGODB_URI:'), 1)
        volumes = '\nvolumes:\n' + ('  postgres-data:\n' if mode == 'bundled' else '') + '  blob-data:\n  symbolicator-cache:\n'
        result[f'deploy/compose.{backend}.{mode}.yml'] = '# Generated by scripts/sync-installer-assets.py; edit shared deploy/compose.yml.\n' + header + (pg_service if mode == 'bundled' else '') + body + volumes
    for profile in ('min', 'low', 'medium', 'high'):
        original = (ROOT / f'deploy/profiles/{profile}.toml').read_text(encoding='utf-8')
        block = '''[storage]
backend = "postgres"

[postgres]
uri = { env = "METRIC_POSTGRES_URI" }
bootstrap_timeout = "30s"
ssl_mode = "verify-full"
max_connections = 10

[postgres.migrations]
mode = "auto"
'''
        generated, count = re.subn(r'\[mongodb\]\n.*?(?=\n\[)', block, original, count=1, flags=re.S)
        if count != 1:
            raise ValueError('Missing unique MongoDB block in profile')
        before, after = tomllib.loads(original), tomllib.loads(generated)
        before.pop('mongodb')
        after.pop('postgres'); after.pop('storage')
        if before != after:
            raise ValueError('Postgres generation changed application profile settings')
        result[f'deploy/profiles/postgres/{profile}.toml'] = '# Generated from the shared resource profile; PostgreSQL sizing is not benchmarked.\n' + generated
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = []
    for relative, content in assets().items():
        path = ROOT / relative
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            changed.append(relative)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding='utf-8', newline='\n')
    if args.check and changed:
        print('Installer assets are stale: ' + ', '.join(changed), file=sys.stderr)
        return 1
    print('Installer assets match shared Compose and resource profiles')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
